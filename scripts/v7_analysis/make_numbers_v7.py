lines: list[str] = ["% Generated by make_numbers_v7.py -- do not edit by hand.", "\\makeatletter"]
seen: set[str] = set()
VAL: dict[str, str] = {}


def m(name: str, value: str, src: str) -> None:
    assert name not in seen, f"duplicate macro {name}"
    assert name.isalpha(), name
    seen.add(name)
    VAL[name] = value
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}} % {src}")


f4 = lambda x: f"{x:.4f}"
s4 = lambda x: f"{x:+.4f}".replace("-", "$-$") if x < 0 else f"{x:+.4f}"


def ci(r: dict, key=("ci_low", "ci_high")) -> str:
    return f"[{s4(r[key[0]])},\\allowbreak\\,{s4(r[key[1]])}]"


def cells(r: dict) -> str:
    return f"{r['cells_positive']}/{r['n_cells']}"


def pval(p: float) -> str:
    return "$<10^{-4}$" if p < 1e-4 else f"{p:.4f}"


def ordinal(x: float) -> str:
    n = int(round(x))
    suf = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suf}"


def contrast(prefix: str, r: dict, src: str) -> None:
    m(prefix, s4(r["estimate"]), src)
    m(prefix + "CI", ci(r), src)
    m(prefix + "TCI", ci(r, ("t_ci_low", "t_ci_high")), src)
    m(prefix + "Cells", cells(r), src)
    m(prefix + "P", pval(r["p_signflip"]), src)


def ms(prefix: str, d: dict, src: str) -> None:
    m(prefix, f"{d['mean']:.4f}", src)
    m(prefix + "SD", f"{d['sd']:.4f}", src)
    m(prefix + "PM", f"{d['mean']:.4f}\\,$\\pm$\\,{d['sd']:.4f}", src)


