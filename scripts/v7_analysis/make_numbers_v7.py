"""Write numbers.tex for the v7 manuscript from result files only. Nothing is typed by hand.

Usage: python make_numbers_v7.py <inputs.json> <out numbers.tex>
<inputs.json> maps names to result files (see INPUTS below); every macro states its source in a comment.
"""
from __future__ import annotations

